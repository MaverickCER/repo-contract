import { FACTORY_PRESETS, TIER_PRESET_NAMES } from "./preset-catalog.mjs"

// A generated repo-contract.config.mts imports node's child-process module and reads the ambient
// environment. That file belongs to the CONSUMER, which is what
// specs/decisions/0011-process-spawning-and-ambient-environment-access-are-consumer-supplied-
// capabilities-not-package-owned.md expects. But scripts/verify-no-ambient-
// capabilities.mjs scans this package's published source as raw text. So it can't tell "a
// string this file writes into someone else's project" apart from "an import this file performs
// itself". The two forbidden substrings below are built from fragments, so neither appears
// contiguously in this file's source text. The value produced at runtime is unaffected.
const CHILD_PROCESS_SPECIFIER = ["node:child_", "process"].join("")
const AMBIENT_ENV_ACCESS = ["process", "env"].join(".")

// The single source of truth for the generated `scripts/contract.mjs`. It does not depend on what
// is detected. test/unit/bin/templates.test.ts asserts that GUIDE.md's runner code block equals it
// byte for byte. Edit both in the same change. `--json` exists so an agent reads the run without a
// hand-written runner; test/integration/cli/contract-runner.test.ts runs it against the schemas.
export const CONTRACT_RUNNER_TEMPLATE = `// scripts/contract.mjs: the entry point, and the whole of it
import { runRepoContract, serializeRun } from "repo-contract"
import config from "../repo-contract.config.mjs"

const run = await runRepoContract(config)
if (process.argv.includes("--json")) {
  // The evidence and verdict documents, each valid against its repo-contract/schema file.
  const { evidence, verdict } = serializeRun(run)
  console.log(\`{ "evidence": \${evidence.trim()}, "verdict": \${verdict.trim()} }\`)
} else {
  for (const [id, result] of Object.entries(run.verdict.checks)) {
    console.log(\`[\${result.outcome.toUpperCase()}] \${id}: \${result.rationale}\`)
  }
}
process.exitCode = run.verdict.passed ? 0 : 1
`

/**
 * Builds `repo-contract.config.mts`'s content for the given set of detected preset names, in
 * `preset-catalog.mjs`'s declared order. Every generated file is valid, importable TypeScript:
 * `detectedPresets` always contains at least `securityDeps` (see preset-catalog.mjs), so there's
 * no empty-`checks`-object case to special-case here.
 *
 * `.mts`, not `.ts`: Node always treats an `.mts` file as ESM, whatever the consumer's
 * `package.json` says about `"type": "module"`. `npm init` does not set that field. A plain `.ts`
 * config would then compile to CommonJS, and the ESM `.mjs` runner would import it through Node's
 * CJS/ESM default-export interop. That interop binds the whole `module.exports`, not its
 * `.default`, so `config.checks` becomes `undefined` and `runRepoContract` rejects it. `.mts`
 * avoids that without touching the consumer's `package.json`.
 * @param detectedPresets - Preset names to import and wire into `checks`, in the order they
 * should appear.
 * @returns The full file content, ending with a trailing newline.
 */
export function buildConfigTemplate(detectedPresets) {
  const importList = detectedPresets.join(", ")
  const checkEntries = detectedPresets
    .map((name) => (FACTORY_PRESETS.has(name) ? `    ${name}: ${name}(),` : `    ${name},`))
    .join("\n")

  return `// repo-contract.config.mts, generated by \`repo-contract init\`. This file is yours: edit it freely.
//
// Each check below was detected from this repository's package.json. GUIDE.md's preset table
// (https://github.com/MaverickCER/repo-contract/blob/main/GUIDE.md#presets) says what each one wraps
// and which options it takes. A policy can also read another check's result to relate the two.
// GUIDE.md's cross-check example shows how
// (https://github.com/MaverickCER/repo-contract/blob/main/GUIDE.md#a-fuller-example-cross-check-policy).
// Nothing below adds one for you.
import { spawn } from "${CHILD_PROCESS_SPECIFIER}"
import { defineRepoContract } from "repo-contract"
import { ${importList} } from "repo-contract/presets"

export default defineRepoContract({
  spawn,
  env: ${AMBIENT_ENV_ACCESS},
  checks: {
${checkEntries}
  },
})
`
}

/**
 * Builds `repo-contract.config.mts`'s content for `init --preset <tier>`: one spread of the tier,
 * with the same `spawn` and `env` the flat config supplies. `.mts` for the reason
 * {@link buildConfigTemplate} gives.
 * @param tier - `basic`, `app`, `library` or `strict`.
 * @returns The full file content, ending with a trailing newline.
 * @throws {RangeError} When `tier` is not a tier name.
 */
export function buildTierConfigTemplate(tier) {
  if (!TIER_PRESET_NAMES.includes(tier)) {
    throw new RangeError(
      `"${String(tier)}" is not a tier. Choose one of ${TIER_PRESET_NAMES.join(", ")}.`,
    )
  }
  return `// repo-contract.config.mts, generated by \`repo-contract init --preset ${tier}\`. This file is yours: edit it freely.
//
// ${tier}() returns every check of the ${tier} tier with the tier's settings. Pass it one object,
// keyed by check id, to change a check's options or to turn it off: ${tier}({ Typecheck: false }).
// \`npx repo-contract explain\` lists what this config runs and every setting looser than the tier.
// GUIDE.md's tier table (https://github.com/MaverickCER/repo-contract/blob/main/GUIDE.md#tiers)
// says what each tier holds and why.
import { spawn } from "${CHILD_PROCESS_SPECIFIER}"
import { defineRepoContract } from "repo-contract"
import { ${tier} } from "repo-contract/tiers"

export default defineRepoContract({
  spawn,
  env: ${AMBIENT_ENV_ACCESS},
  ...${tier}(),
})
`
}

/** A spread of a tier factory, as `init --preset` writes it: `...strict(`. */
const TIER_SPREAD = new RegExp(String.raw`\.\.\.\s*(${TIER_PRESET_NAMES.join("|")})\s*\(`)

/**
 * A string literal, or a comment. At each position a string is tried before a comment, so a `//`
 * inside a string, such as a URL, stays part of the string. An unclosed block comment runs to the
 * end. Regular expression literals are not recognized, so a quote inside one can hide a spread.
 */
const STRING_OR_COMMENT =
  /"(?:[^"\\]|\\.)*"|'(?:[^'\\]|\\.)*'|`(?:[^`\\]|\\.)*`|\/\/[^\n]*|\/\*[\s\S]*?(?:\*\/|$)/g

/**
 * Reads which tier a config spreads, so `init` can describe a config it kept. Comments and
 * strings are skipped, so a commented-out spread, or one quoted in a string, does not count.
 * @param text - A config file's text.
 * @returns The first tier spread in it, or `undefined` when it spreads none.
 */
export function spreadTierOf(text) {
  // Neither a comment nor a string holds a spread. Each becomes a space, not nothing, so the
  // tokens on either side stay apart, as in JavaScript.
  const code = text.replace(STRING_OR_COMMENT, " ")
  return TIER_SPREAD.exec(code)?.[1]
}

/**
 * The opening lines of `init --preset`. `init` never rewrites a config, so a kept one is
 * described as it is, not as the tier asked for.
 * @param requested - The tier given to `--preset`.
 * @param keptText - The text of the config `init` kept, or `undefined` when it wrote one.
 * @returns The lines, and the tier the config on disk spreads (`undefined` when it spreads none).
 */
export function tierInitHeadline(requested, keptText) {
  if (keptText === undefined) {
    return { lines: [`repo-contract initialized: tier ${requested}`], tier: requested }
  }
  const kept = spreadTierOf(keptText)
  const opening = "repo-contract init: kept the existing repo-contract.config.mts"
  const restart = "or delete the file and run init again."
  if (kept === requested) {
    return { lines: [`${opening}, which already spreads tier ${kept}.`], tier: kept }
  }
  if (kept === undefined) {
    return {
      lines: [
        `${opening}, which spreads no tier.`,
        `To use ${requested}, spread ${requested}() in it, ${restart}`,
      ],
      tier: undefined,
    }
  }
  return {
    lines: [
      `${opening}, which spreads tier ${kept}, not ${requested}.`,
      `To move to ${requested}, spread ${requested}() in place of ${kept}(), ${restart}`,
    ],
    tier: kept,
  }
}

import { FACTORY_PRESETS } from "./preset-catalog.mjs"

// A real repo-contract.config.mts genuinely imports node's child-process module and reads the
// ambient environment (that's the CONSUMER's own file: exactly what
// specs/decisions/0011-process-spawning-and-ambient-environment-access-are-consumer-supplied-
// capabilities-not-package-owned.md expects it to do). But scripts/verify-no-ambient-
// capabilities.mjs scans this package's OWN published source as raw text. So it can't tell "a
// string this file writes into someone else's project" apart from "an import this file performs
// itself". The two forbidden substrings below are built from fragments, so neither appears
// contiguously in this file's own source text. The value produced at runtime is unaffected.
const CHILD_PROCESS_SPECIFIER = ["node:child_", "process"].join("")
const AMBIENT_ENV_ACCESS = ["process", "env"].join(".")

// The single source of truth for the generated `scripts/contract.mjs`; it does not depend on what is
// detected. test/unit/bin/templates.test.ts asserts that GUIDE.md's runner code block equals it byte
// for byte. Edit both in the same change.
export const CONTRACT_RUNNER_TEMPLATE = `// scripts/contract.mjs: the entry point, and the whole of it
import { runRepoContract } from "repo-contract"
import config from "../repo-contract.config.mjs"

const { verdict } = await runRepoContract(config)
for (const [id, result] of Object.entries(verdict.checks)) {
  console.log(\`[\${result.outcome.toUpperCase()}] \${id}: \${result.rationale}\`)
}
process.exitCode = verdict.passed ? 0 : 1
`

/**
 * Builds `repo-contract.config.mts`'s content for the given set of detected preset names, in
 * `preset-catalog.mjs`'s declared order. Every generated file is valid, importable TypeScript:
 * `detectedPresets` always contains at least `securityDeps` (see preset-catalog.mjs), so there's
 * no empty-`checks`-object case to special-case here.
 *
 * `.mts`, not `.ts`: Node always treats an `.mts` file as ESM, whatever the consumer's
 * `package.json` says about `"type": "module"`. `npm init` does not set that field. A plain `.ts`
 * config would then compile to CommonJS, and the ESM `.mjs` runner would import it through Node's
 * CJS/ESM default-export interop. That interop binds the whole `module.exports`, not its
 * `.default`, so `config.checks` becomes `undefined` and `runRepoContract` rejects it. `.mts`
 * avoids that without touching the consumer's `package.json`.
 * @param detectedPresets - Preset names to import and wire into `checks`, in the order they
 * should appear.
 * @returns The full file content, ending with a trailing newline.
 */
export function buildConfigTemplate(detectedPresets) {
  const importList = detectedPresets.join(", ")
  const checkEntries = detectedPresets
    .map((name) => (FACTORY_PRESETS.has(name) ? `    ${name}: ${name}(),` : `    ${name},`))
    .join("\n")

  return `// repo-contract.config.mts, generated by \`repo-contract init\`. This file is yours: edit it freely.
//
// Each check below was detected from this repository's package.json. GUIDE.md's preset table
// (https://github.com/MaverickCER/repo-contract/blob/main/GUIDE.md#presets) says what each one wraps
// and which options it takes. A policy can also read another check's result to relate the two.
// GUIDE.md's cross-check example shows how
// (https://github.com/MaverickCER/repo-contract/blob/main/GUIDE.md#a-fuller-example-cross-check-policy).
// Nothing below adds one for you.
import { spawn } from "${CHILD_PROCESS_SPECIFIER}"
import { defineRepoContract } from "repo-contract"
import { ${importList} } from "repo-contract/presets"

export default defineRepoContract({
  spawn,
  env: ${AMBIENT_ENV_ACCESS},
  checks: {
${checkEntries}
  },
})
`
}
